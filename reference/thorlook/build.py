#!/usr/bin/env python3
"""Build ThorLook's Decky front end: decky/index.template.js + art/*.svg ->
decky/dist/index.js, with each picture embedded as a data URI (no node build,
no files served at runtime).

    python build.py            # build
    python build.py --check    # build to memory and compare with dist/index.js
"""
from __future__ import annotations

import base64
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TEMPLATE = HERE / "decky" / "index.template.js"
OUT = HERE / "decky" / "dist" / "index.js"
ART_DIR = HERE.parent.parent / "art"   # the repo's art/ folder
GLYPH_DIR = ART_DIR / "glyphs"


def find_art(name: str) -> Path:
    """art/<name>, or art/glyphs/<name> for the button icons."""
    return ART_DIR / name if (ART_DIR / name).is_file() else GLYPH_DIR / name

# ART key -> candidate files in art/, first one present wins.
ART = {
    "controller": ["thor_lower_animated.svg", "thor_lower.svg"],
    "glyph_home": ["glyph_home_steam.svg", "glyph_home_dark.svg"],
    "glyph_start": ["glyph_triangle_steam.svg", "glyph_triangle_dark.svg"],
    "glyph_select": ["glyph_square_steam.svg", "glyph_square_dark.svg"],
    "glyph_quick_access": ["glyph_back_qam_steam.svg", "glyph_back_qam_dark.svg"],
    # Calibration screen (art/make_calibration.py derives these from thor_lower.svg)
    "cal_left": ["thor_cal_left.svg"],
    "cal_right": ["thor_cal_right.svg"],
}


# Drawings inlined as SVG markup (their ids get a tl_ / tla_ prefix at runtime):
# the live input-test drawing, and the animated one for the game-launch screen
# (inline, not an <img>, so its intro can be restarted).
SVG_TEXT = {"controller": "thor_lower.svg", "launch": "thor_lower_animated.svg"}


def data_uri(path: Path) -> str:
    raw = path.read_bytes()
    return "data:image/svg+xml;base64," + base64.b64encode(raw).decode("ascii")


def build() -> str:
    art: dict[str, str | None] = {}
    for key, names in ART.items():
        found = next((find_art(n) for n in names if find_art(n).is_file()), None)
        art[key] = data_uri(found) if found else None
        print(f"  {key}: {found.name if found else 'MISSING'}", file=sys.stderr)
    template = TEMPLATE.read_text(encoding="utf-8")
    marker = "/* @ART@ */"
    if marker not in template:
        sys.exit(f"{TEMPLATE}: no {marker} marker")
    # Raw SVG markup for drawings inserted into Steam's DOM (live input test).
    raw: dict[str, str | None] = {}
    for key, name in SVG_TEXT.items():
        path = ART_DIR / name
        text = path.read_text(encoding="utf-8") if path.is_file() else ""
        text = re.sub(r"<\?xml[^>]*>\s*|<title[^>]*>.*?</title>", "", text, flags=re.S).strip()
        raw[key] = text or None
        print(f"  svg {key}: {name if text else 'MISSING'}", file=sys.stderr)
    block = ("// Generated by build.py from art/*.svg\nconst ART = " + json.dumps(art, indent=1) + ";\n"
             "const ART_SVG = " + json.dumps(raw) + ";")
    header = "// GENERATED by reference/thorlook/build.py: edit index.template.js and art/, then rebuild.\n"
    return header + template.replace(marker, block)


def main() -> int:
    js = build()
    if "--check" in sys.argv[1:]:
        same = OUT.is_file() and OUT.read_text(encoding="utf-8") == js
        print("dist/index.js is " + ("up to date" if same else "STALE"))
        return 0 if same else 1
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(js, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(js) // 1024} KB)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
