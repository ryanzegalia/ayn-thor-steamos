const BACK_BUTTON_IMGS = 'img[src*="/sd_l4."],img[src*="/sd_l5."],img[src*="/sd_r4."],img[src*="/sd_r5."]';
function hideBackButtonRows(root) {
    for (const img of Array.from(root.querySelectorAll(BACK_BUTTON_IMGS))) {
        if (!/\/sd_[lr][45]\.(svg|png)$/.test(img.getAttribute("src") || "")) continue;
        // The row: the nearest ancestor ending in its true/false value. Not
        // found (yet) = hide nothing, never a bigger piece of the page.
        const isRow = (el) => /^(true|false)$/.test(el.textContent.trim().split(/\s+/).pop() || "");
        let row = img.parentElement;
        for (let i = 0; row && i < 4 && !isRow(row); i++) row = row.parentElement;
        if (row && isRow(row) && row.style.display !== "none") row.style.display = "none";
    }
}

function nearestControl(x, y, controls = PRO_CONTROLS) {
    let best = null, bestD = 26 * 26;
    for (const [cx, cy, id] of controls) {
        const d = (cx - x) ** 2 + (cy - y) ** 2;
        if (d < bestD) { bestD = d; best = id; }
    }
    return best;
}

function liveTest(doc) {
    let drawing = null;
    const svg = Array.from(doc.querySelectorAll(DRAWING_SEL)).find((s) => {
        if (s.__thorlook) return false;
        drawing = DRAWINGS.find((d) => s.matches(d.sel));
        return drawing && s.querySelectorAll(drawing.parts).length >= 12;
    });
    if (!svg || !ART_SVG.controller) return;
    const snap = (p) => drawing.attrs.map((a) => p.getAttribute(a) || "").join("|");
    const links = [];
    for (const p of Array.from(svg.querySelectorAll(drawing.parts))) {
        let b;
        try { b = p.getBBox(); } catch (e) { continue; }
        const id = nearestControl(b.x + b.width / 2, b.y + b.height / 2, drawing.controls);
        if (id) links.push({ p, id, rest: snap(p) });
    }
    if (links.length < 8) {  // not laid out yet, or some other drawing: try again on later ticks
        svg.__thorlookTries = (svg.__thorlookTries || 0) + 1;
        if (svg.__thorlookTries >= 3) svg.__thorlook = true;
        return;
    }
    svg.__thorlook = true;
    const holder = doc.createElement("div");
    holder.innerHTML = ART_SVG.controller;
    const ours = holder.querySelector("svg");
    if (!ours) return;
    for (const el of Array.from(ours.querySelectorAll("[id]"))) el.id = "tl_" + el.id;
    ours.setAttribute("class", (svg.getAttribute("class") || "") + " tl-live-svg" + (drawing.kind === "handheld" ? " tl-handheld" : ""));
    ours.setAttribute("preserveAspectRatio", "xMidYMid meet");
    ours.setAttribute("viewBox", SIDE_VIEWBOX);
    ours.insertAdjacentHTML("beforeend", SIDE_SVG);
    if (drawing.kind === "handheld") {
        // Steam sizes its handheld drawing for the Deck's wide shape; give the Thor the room the Pro screen has
        ours.style.setProperty("height", "160px", "important");
        ours.style.setProperty("transform", "none", "important");
    }
    svg.style.display = "none";
    svg.parentNode.insertBefore(ours, svg.nextSibling);
    const els = new Map(links.map((l) => [l.id, ours.querySelector("#tl_" + l.id)]));
    const pro = drawing.kind === "pro";
    // Steam's handheld drawing has no D-pad: the backend reads it off the Thor.
    if (!pro) for (const d of DPAD) els.set("dpad_" + d, ours.querySelector("#tl_dpad_" + d));
    // Steam's Switch Pro drawing has no ZL/ZR: read the screen's own
    // "Left Trigger" / "Right Trigger" rows instead (0 at rest).
    // Found once they exist (they may render a moment after the drawing).
    const triggers = [];
    const sticks = [];
    const findTriggers = () => {
        if (triggers.length || !svg.parentNode) return;
        if (drawing.kind === "handheld") hideBackButtonRows(doc);
        // The rows sit beside the drawing (Pro screen) or further up the page (handheld)
        let scope = svg.parentNode;
        for (let i = 0; i < 6 && scope && !scope.textContent.includes("Left Trigger"); i++) scope = scope.parentElement;
        if (!scope) return;
        for (const el of Array.from(scope.querySelectorAll("div"))) {
            const t = el.childElementCount === 0 && el.textContent.trim();
            if ((t === "Left Joystick" || t === "Right Joystick") && drawing.sticks === "rows") {
                let row = el.parentElement;
                for (let i = 0; row && i < 4 && row.textContent.trim() === t; i++) row = row.parentElement;
                if (row && row.textContent.trim() !== t) {
                    sticks.push({ id: t === "Left Joystick" ? "lstick" : "rstick", row, label: t });
                    new doc.defaultView.MutationObserver(() => sync())
                        .observe(row, { subtree: true, childList: true, characterData: true });
                }
                continue;
            }
            const id = t === "Left Trigger" ? "btn_zl" : t === "Right Trigger" ? "btn_zr" : null;
            // The row: the nearest ancestor that also holds the value.
            let row = el.parentElement;
            for (let i = 0; row && i < 4 && row.textContent.trim() === t; i++) row = row.parentElement;
            if (!id || !row || row.textContent.trim() === t) continue;
            triggers.push({ id, row, label: t });
            els.set(id, ours.querySelector("#tl_" + id));
            new doc.defaultView.MutationObserver(() => sync())
                .observe(row, { subtree: true, childList: true, characterData: true });
        }
    };
    // Switch Pro identity: Steam sees the Quick Access chord as Home + B: draw
    // it as the Thor's own Quick Access button. When Home shows up, ask the
    // backend which of the Thor's buttons was really pressed (a few ms); hold
    // the house until then. The handheld identity has real Home and Quick
    // Access buttons, so its drawing just follows Steam's.
    const qam = pro && ours.querySelector("#tl_btn_back_qam");
    let keysOk = false;
    const keepWatching = () => {
        if (!ours.isConnected) { clearInterval(watchTimer); return; }
        watchKeys().then(() => { keysOk = true; }).catch(() => { keysOk = false; });
    };
    const watchTimer = setInterval(keepWatching, 60000);
    keepWatching();
    let dpad = "", dpadBusy = false;
    if (!pro) {
        const dpadTimer = setInterval(() => {
            if (!ours.isConnected) { clearInterval(dpadTimer); return; }
            if (!keysOk || dpadBusy) return;
            dpadBusy = true;
            padKeys().then((r) => {
                dpadBusy = false;
                const held = ((r && r.dpad) || []).join(",");
                if (held !== dpad) { dpad = held; sync(); }
            }).catch(() => { dpadBusy = false; });
        }, DPAD_POLL_MS);
    }
    let homeAt = 0, bAt = 0, wasHome = false, wasB = false, chord = false, homeTimer = 0, asked = 0, answer = null;
    const sync = () => {
        findTriggers();
        const down = new Set();
        for (const l of links) {
            if (snap(l.p) !== l.rest) down.add(l.id);
        }
        for (const d of dpad ? dpad.split(",") : []) down.add("dpad_" + d);
        for (const t of triggers) {
            const m = /\d+/.exec(t.row.textContent.replace(t.label, ""));
            const v = m ? Math.min(1, parseInt(m[0], 10) / 32767) : 0;
            // The meter alone shows the pull (marking the trigger
            // pressed at half pull painted it full from ~17,000). The label
            // turns dark once the meter covers it, to stay readable.
            const meter = ours.querySelector(`#tl_${t.id} .tl-meter`);
            if (meter) { meter.setAttribute("y", (-T_H * v).toFixed(1)); meter.setAttribute("height", (T_H * v).toFixed(1)); }
            const g = els.get(t.id);
            if (g) g.classList.toggle("tl-covered", v >= LABEL_COVER);
        }
        const now = Date.now();
        const home = down.has("btn_home"), b = down.has("btn_b");
        if (pro && home && !wasHome) {
            homeAt = now;
            answer = keysOk ? null : "?";
            if (keysOk) {
                const ask = ++asked;
                padKeys().then((r) => {
                    if (ask !== asked) return;
                    if (!r || !r.watching) { keysOk = false; answer = "?"; }
                    // Quick Access pressed just now, and after Home: the chord
                    else answer = r.qam_ms != null && r.qam_ms < 400 && (r.home_ms == null || r.qam_ms <= r.home_ms) ? "qam" : "home";
                    sync();
                }).catch(() => { if (ask === asked) { keysOk = false; answer = "?"; sync(); } });
            }
        }
        if (b && !wasB) bAt = now;
        wasHome = home; wasB = b;
        if (pro && home && !chord) {
            if (answer === "qam") chord = true;
            else if (answer === "?" && b && bAt >= homeAt && bAt - homeAt <= CHORD_MS) chord = true;
        }
        if (chord && !home && !b) chord = false;
        let showHome = pro ? home && !chord && answer !== null : home;
        if (pro && showHome && answer === "?" && now - homeAt < CHORD_MS) {
            showHome = false;
            if (!homeTimer) homeTimer = setTimeout(() => { homeTimer = 0; sync(); }, CHORD_MS - (now - homeAt) + 5);
        }
        for (const [id, el] of els) {
            if (!el) continue;
            let on = down.has(id);
            if (id === "btn_home") on = showHome;
            else if (id === "btn_b" && chord) on = false;
            el.classList.toggle("tl-pressed", on);
        }
        if (qam) qam.classList.toggle("tl-pressed", chord);
        for (const st of sticks) {
            const el = els.get(st.id) || ours.querySelector("#tl_" + st.id);
            const m = /(-?[\d.]+)\s*,\s*(-?[\d.]+)/.exec(st.row.textContent.replace(st.label, ""));
            if (!el || !m) continue;
            const scale = (v) => Math.max(-1, Math.min(1, Math.abs(v) > 1.5 ? v / 32767 : v));
            el.style.transform = `translate(${(scale(+m[1]) * STICK_TRAVEL).toFixed(2)}px, ${(-scale(+m[2]) * STICK_TRAVEL).toFixed(2)}px)`;
        }
        for (const l of links) {
            const el = els.get(l.id);
            if (!el || drawing.sticks !== "style") continue;
            if (l.id === "lstick" || l.id === "rstick") {
                const m = /translateX\(([-\d.e+]+)%\)\s*translateY\(([-\d.e+]+)%\)/.exec(l.p.getAttribute("style") || "");
                const dx = m ? parseFloat(m[1]) * 10 * STICK_SCALE : 0;    // % of 1000
                const dy = m ? parseFloat(m[2]) * 7.02 * STICK_SCALE : 0;  // % of 702
                el.style.transform = `translate(${dx.toFixed(2)}px, ${dy.toFixed(2)}px)`;
            }
        }
    };
    new doc.defaultView.MutationObserver(sync)
        .observe(svg, { subtree: true, attributes: true, attributeFilter: drawing.attrs });
    sync();
    log(`live Thor drawing on the ${drawing.kind} input test screen (${links.length} controls)`);
}

// ---- Steam calls the Thor "AYN Thor" ----
// Steam's own "Controller Name" setting (saved per controller). Only the
// Thor's virtual Pro Controller, matched by its serial (NSP + the MAC our
// InputPlumber target derives from /etc/machine-id), and only while it still
// has Steam's default name, so a real Pro Controller or a name the user picked is
// never touched.
const THOR_NAME = "AYN Thor";
const thorSerial = api.callable("thor_serial");
// Two things only Steam's UI modules hold: its controller store, and the
// launch screen's CSS-module class names. One walk finds both.
let controllerStore = null;
let launchCls = null;      // the launch screen's ControllerInterstitialAnimationContainer class
let summaryCls = null;     // the layout preview's class names (ControllerConfiguratorSummary module)
let moduleScanAt = 0;
function scanModules() {
    if (controllerStore && launchCls && summaryCls) return;
    // Walking every UI module is not free: at most once a minute until found.
    if (Date.now() - moduleScanAt < 60000) return;
    moduleScanAt = Date.now();
    const req = window.webpackChunksteamui.push([[Symbol("thorlook")], {}, (r) => r]);
    const look = (v) => {
        if (!v || typeof v !== "object") return;
        if (!controllerStore && "m_controllerList" in v) controllerStore = v;
        if (!launchCls && typeof v.ControllerInterstitialAnimationContainer === "string")
            launchCls = v.ControllerInterstitialAnimationContainer.split(" ")[0];
        if (!summaryCls && typeof v.ControllerConfiguratorSummary === "string" && typeof v.BackgroundController === "string")
            summaryCls = v;
    };
    for (const id of Object.keys(req.m)) {
        let e;
        try { e = req(id); } catch (x) { continue; }
        if (!e || typeof e !== "object") continue;
        look(e);
        for (const k of Object.keys(e)) {
            let v;
            try { v = e[k]; } catch (x) { continue; }
            look(v);
        }
        if (controllerStore && launchCls && summaryCls) break;
    }
}

// ---- The layout preview (Steam menu during a game, View Layout) ----
// Steam lays it out at full size, lets its top row stretch to fill the panel
// and then shrinks the whole thing (inline zoom ~0.72), so the Thor sits small
// in empty space with 10px labels. This tighter version was approved on the device
// (prototyped live in the in-game menu): top row fixed to the drawing, narrower
// side columns, zoom 0.85 (Steam's 0.72), bigger labels, and no rows for controls the Thor
// lacks (back buttons L4/L5/R4/R5, trackpads).
function summaryCss(c) {
    const k = (name) => "." + String(c[name] || "").split(" ")[0];
    const S = k("ControllerConfiguratorSummary");
    if (S === ".") return "";
    const missing = 'img[src$="/sd_l4.svg"], img[src$="/sd_l5.svg"], img[src$="/sd_r4.svg"], img[src$="/sd_r5.svg"], img[src*="trackpad"]';
    // Size: only where Steam shrinks it (inline zoom, a fixed ~0.72 in the in-game
    // menu; Steam does not re-measure, tested 10-14), not the full-page View Layout.
    // With the menu's sidebar expanded Steam pushes the panel off the right edge
    // either way, its own 0.72 included.
    return `${S}[style*="zoom"] { zoom: 0.85 !important; width: 700px !important; flex-grow: 0 !important; }
${S} ${k("ControlContainer")}:has(${missing}) { display: none !important; }
${S} ${k("ControlsListSection")}:has(img[src*="trackpad"]) { display: none !important; }
${S} ${k("TopSection")} { flex: 0 0 300px !important; height: 300px !important; }
${S} ${k("Left")}, ${S} ${k("Right")} { width: 165px !important; height: 300px !important; }
${S} ${k("ControlContainer")} { width: 165px !important; }
${S} ${k("Center")} { width: 370px !important; height: 300px !important; }
${S} ${k("BackgroundController")} { height: 300px !important; width: 370px !important; }
${S} ${k("ControllerInputDisplay")} { font-size: 14px !important; }
${S} ${k("Title")}, ${S} ${k("TitleLabel")} { font-size: 13px !important; }
${S} ${k("BottomControlsSections")} { margin-top: 16px !important; }
`;
}
let summaryDone = false;
function applySummaryCss() {
    if (summaryDone || !summaryCls) return;
    const css = summaryCss(summaryCls);
    if (!css) return;
    summaryDone = true;
    for (const d of steamDocuments()) {
        const st = d.getElementById(STYLE_ID);
        if (st && !st.textContent.includes(css)) st.textContent += css;
    }
    const main = document.getElementById(STYLE_ID);
    if (main) sharePopupCss(main.textContent);   // Steam menu, Quick Access, Controller Layout windows
    log("layout preview CSS applied");
}
function findControllerStore() {
    scanModules();
    return controllerStore;
}
// The Thor's own pad: InputPlumber's handheld (28de:12f0, or 12f1 with pb-os
// patch 0003) or our virtual Pro Controller (its serial ends with the Thor's MAC).
function isThorPad(p, serial) {
    if (!p) return false;
    if (p.unVendorID === 0x28de && (p.unProductID === 0x12f0 || p.unProductID === 0x12f1)) return true;
    const sn = String(p.strSerialNumber || "").toLowerCase();
    return p.unVendorID === 0x057e && p.unProductID === 0x2009 && !!serial && sn.endsWith(serial);
}
let serialPromise = null;
let thorSerialText = "";
async function nameThor() {
    try {
        if (!serialPromise) serialPromise = thorSerial();
        const serial = (await serialPromise || "").toLowerCase();
        thorSerialText = serial;
        const store = serial && findControllerStore();
        if (!store) return;
        const l = store.m_controllerList;
        const pads = Array.isArray(l) ? l : (l && typeof l.values === "function" ? Array.from(l.values()) : Object.values(l || {}));
        for (const p of pads) {
            if (!isThorPad(p, serial)) continue;
            // Only Steam's default name, never one the user picked
            const pro = p.unVendorID === 0x057e && p.strName === "Nintendo Switch Pro Controller";
            const handheld = p.unVendorID === 0x28de && p.strName !== THOR_NAME && /steam/i.test(String(p.strName || ""));
            if (pro || handheld) {
                SteamClient.Input.SetControllerName(p.nControllerIndex, THOR_NAME);
                log(`named controller ${p.nControllerIndex} "${THOR_NAME}"`);
            }
        }
    } catch (e) { log("naming failed", e); }
}

// ---- The animated Thor on the game-launch screen ----
// While a game starts, Steam shows the controller it will use above "This game
// will use ...": a looping <video> (/movies/<steamdeck|steam_controller|
// controller_generic>_*.webm) or, with nothing to animate, a still <img>, in a
// ControllerInterstitialAnimationContainer box (30vh high). When that
// controller is the Thor, hide Steam's picture and draw the Thor there instead,
// sized like Steam's own inline Legion Go S drawing (75% of the box). Our
// drawing's intro (2.2 s of SMIL) plays once, so restart it every few seconds.
const LAUNCH_VIDEO_RE = /^\/movies\/(steamdeck|steam_controller|controller_generic)_[a-z_]+\.webm$/;
const LAUNCH_STILL_RE = /^(\/images\/(controller_generic|steam_controller_still)\.png|data:image\/png;)/;
const LAUNCH_RESTART_MS = 3000;
function thorIsActive() {
    try {
        const p = window.SteamUIStore && window.SteamUIStore.MostRecentlyActiveController;
        return p ? isThorPad(p, thorSerialText) : true;  // unknown: this is a Thor plugin
    } catch (e) { return true; }
}
function launchPicture(doc) {
    if (!ART_SVG.launch) return;
    // A picture Steam has dropped (another game, config change) takes ours with it.
    for (const ours of Array.from(doc.querySelectorAll("svg.tl-launch"))) {
        if (!ours.__thorlookFor || !ours.__thorlookFor.isConnected) ours.remove();
    }
    // On the handheld identity Steam draws neither: it puts its own animated
    // handheld drawing there as an inline <svg> (10-14, Balatro).
    const sel = launchCls ? `.${launchCls} > video, .${launchCls} > img, .${launchCls} > svg:not(.tl-launch)` : "video";
    for (const el of Array.from(doc.querySelectorAll(sel))) {
        if (el.__thorlook) continue;
        if (el.tagName === "VIDEO") {
            const src = (el.querySelector("source") || el).getAttribute("src") || "";
            if (!LAUNCH_VIDEO_RE.test(src)) continue;
        } else if (el.tagName === "IMG" && !LAUNCH_STILL_RE.test(el.getAttribute("src") || "")) continue;
        if (!thorIsActive()) continue;  // a pad plugged in: leave Steam's picture of it
        const holder = doc.createElement("div");
        holder.innerHTML = ART_SVG.launch;
        const ours = holder.querySelector("svg");
        if (!ours) return;
        for (const n of Array.from(ours.querySelectorAll("[id]"))) n.id = "tla_" + n.id;
        ours.removeAttribute("width");
        ours.removeAttribute("height");
        ours.setAttribute("class", "tl-launch");
        ours.setAttribute("preserveAspectRatio", "xMidYMid meet");
        ours.__thorlookFor = el;
        el.__thorlook = ours;
        el.style.display = "none";
        if (typeof el.pause === "function") el.pause();
        el.parentNode.insertBefore(ours, el.nextSibling);
        const timer = setInterval(() => {
            if (!ours.isConnected || !el.isConnected) { clearInterval(timer); if (!el.isConnected) ours.remove(); return; }
            try { ours.setCurrentTime(0); } catch (e) { clearInterval(timer); }
        }, LAUNCH_RESTART_MS);
        log("animated Thor on the launch screen in place of Steam's", el.tagName.toLowerCase());
    }
}

// ---- Steam's words: "AYN Thor", not "Nintendo Switch Pro controller" ----
// Steam names the controller type in running text (the Steam Input intro,
// configurator headings). Replace that phrase in text nodes as they appear.
const RENAME_RE = /Nintendo Switch Pro [Cc]ontroller/g;
function renameText(root) {
    const walker = root.ownerDocument.createTreeWalker(root, 4 /* SHOW_TEXT */);
    for (let n = walker.nextNode(); n; n = walker.nextNode()) {
        if (n.nodeValue && n.nodeValue.includes("Switch Pro")) n.nodeValue = n.nodeValue.replace(RENAME_RE, THOR_NAME);
    }
}
function watchText(doc) {
    if (!doc || !doc.body || doc.__thorlookText) return;
    renameText(doc.body);
    const obs = new doc.defaultView.MutationObserver((muts) => {
        let drawing = false, launch = false;
        for (const m of muts) {
            if (m.type === "characterData") {
                const n = m.target;
                if (n.nodeValue && n.nodeValue.includes("Switch Pro")) n.nodeValue = n.nodeValue.replace(RENAME_RE, THOR_NAME);
            } else {
                for (const node of m.addedNodes) {
                    if (node.nodeType === 3) {
                        if (node.nodeValue.includes("Switch Pro")) node.nodeValue = node.nodeValue.replace(RENAME_RE, THOR_NAME);
                    } else if (node.nodeType === 1) {
                        renameText(node);
                        if (node.matches(DRAWING_SEL) || node.querySelector(DRAWING_SEL)) drawing = true;
                        if (node.matches(BACK_BUTTON_IMGS) || node.querySelector(BACK_BUTTON_IMGS)) hideBackButtonRows(doc);
                        if (node.tagName === "VIDEO" || node.tagName === "IMG" || node.querySelector("video")
                            || (launchCls && (node.querySelector("." + launchCls)
                                || (node.parentElement && node.parentElement.classList.contains(launchCls))))) launch = true;
                    }
                }
            }
        }
        // Swap the drawing in before Steam's Switch Pro is ever painted
        // (observer callbacks run before the next frame).
        if (drawing) liveTest(doc);
        if (launch) launchPicture(doc);
    });
    obs.observe(doc.body, { childList: true, subtree: true, characterData: true });
    doc.__thorlookText = obs;
}

let timer = null;
function start() {
    const tick = () => {
        for (const d of steamDocuments()) { watchDocument(d); liveTest(d); watchText(d); launchPicture(d); }
        nameThor().then(applySummaryCss);
    };
    tick();
    // New windows appear over time; cheap to re-check.
    timer = setInterval(tick, 3000);
}

function stop() {
    if (timer) clearInterval(timer);
    timer = null;
    for (const d of steamDocuments()) {
        const s = d.getElementById(STYLE_ID);
        if (s) s.remove();
        if (d.__thorlookObserver) d.__thorlookObserver.disconnect();
        delete d.__thorlookObserver;
        delete d.__thorlookSeen;
        for (const ours of Array.from(d.querySelectorAll("svg.tl-launch"))) {
            const el = ours.__thorlookFor;
            if (el) { el.style.display = ""; delete el.__thorlook; }
            ours.remove();
        }
    }
}

