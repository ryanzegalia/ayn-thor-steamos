function glyphCss() {
    return GLYPHS.concat(IMAGES).filter((g) => g.art).map((g) =>
        `img[src$="/${g.steam}.svg"],img[src$="/${g.steam}.png"]{content:url("${g.art}") !important;}`
    ).join("\n") + "\n";
}

// Every CSS rule in a document whose background image is one of Steam's
// controller pictures we replace, as [selectorText, art].
function findRules(doc) {
    const found = [];
    for (const sheet of Array.from(doc.styleSheets || [])) {
        let rules;
        try { rules = sheet.cssRules; } catch (e) { continue; }  // cross-origin sheet
        for (const rule of Array.from(rules || [])) {
            const bg = rule.style && rule.style.backgroundImage;
            if (!bg || !rule.selectorText) continue;
            for (const r of REPLACE) {
                if (bg.includes(r.steam)) found.push([rule.selectorText, r.art]);
            }
        }
    }
    return found;
}

// Quick Access, the main menu and toasts are separate browser windows this
// front end cannot reach; the backend injects the same CSS there over Steam's
// local debugger (what CSS Loader does).
const setPopupCss = api.callable("set_popup_css");
let sharedCss = "";
function sharePopupCss(css) {
    if (!css || css === sharedCss) return;
    sharedCss = css;
    setPopupCss(css).catch((e) => log("popup css failed", e));
}

// Our override style in a document, created with the glyph rules.
function ensureStyle(doc) {
    let style = doc.getElementById(STYLE_ID);
    if (!style) {
        style = doc.createElement("style");
        style.id = STYLE_ID;
        style.textContent = glyphCss() + LIVE_CSS + (summaryDone && summaryCls ? summaryCss(summaryCls) : "");
        doc.head.appendChild(style);
        if (doc === document || (DFL.findSP && DFL.findSP() && doc === DFL.findSP().document)) sharePopupCss(style.textContent);
    }
    return style;
}

// Add (or extend) our override style in a document.
function patchDocument(doc) {
    if (!doc || !doc.head) return 0;
    const style = ensureStyle(doc);
    const rules = findRules(doc);
    if (!doc.__thorlookSeen) doc.__thorlookSeen = new Set();
    const fresh = rules.filter(([sel]) => !doc.__thorlookSeen.has(sel));
    if (!fresh.length) return 0;
    for (const [sel, art] of fresh) {
        style.textContent += `${sel}{background-image:url("${art}") !important;}\n`;
        doc.__thorlookSeen.add(sel);
    }
    log(`patched ${fresh.length} rule(s)`, fresh.map(([s]) => s));
    sharePopupCss(style.textContent);
    return fresh.length;
}

// Steam loads its controller-page CSS lazily: watch each document's <head>
// for new stylesheets and patch again once they have loaded.
function watchDocument(doc) {
    if (!doc || !doc.head || doc.__thorlookObserver) return;
    patchDocument(doc);
    const obs = new doc.defaultView.MutationObserver((muts) => {
        for (const m of muts) {
            for (const node of m.addedNodes) {
                if (node.id === STYLE_ID) continue;
                if (node.tagName === "LINK") node.addEventListener("load", () => patchDocument(doc), { once: true });
                if (node.tagName === "STYLE" || node.tagName === "LINK") setTimeout(() => patchDocument(doc), 50);
            }
        }
    });
    obs.observe(doc.head, { childList: true });
    doc.__thorlookObserver = obs;
}

// Steam's windows: the Game Mode main window, plus any popup windows Steam
// opens (overlay, keyboard, modal windows).
function steamDocuments() {
    const docs = new Set([document]);
    try {
        const sp = DFL.findSP && DFL.findSP();
        if (sp && sp.document) docs.add(sp.document);
    } catch (e) { log("findSP failed", e); }
    try {
        const store = window.SteamUIStore && window.SteamUIStore.WindowStore;
        const wins = store && (store.SteamUIWindows || []);
        for (const w of wins) {
            const d = w && (w.m_BrowserWindow ? w.m_BrowserWindow.document : (w.BrowserWindow && w.BrowserWindow.document));
            if (d) docs.add(d);
        }
    } catch (e) { log("window list failed", e); }
    return Array.from(docs);
}

